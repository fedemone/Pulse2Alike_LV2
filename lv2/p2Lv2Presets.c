// Notes: Docs/code-notes/p2Lv2.md - "// notes §k" refers there.
//
// usage: p2Lv2Presets <sounds> <manifest.ttl> <bundle directory>
//
// notes §15: <sounds> is what the desktop plug-in's Import Presets reads - a .syx of one or many sound dumps (its
// presets.syx, an instrument's backup), or a folder of "NNN Name.syx". Each sound becomes preset PNNN of the slot it is
// addressed to; the bundle's manifest.ttl is <manifest.ttl> with the presets added, and they are in presets.ttl.
// make -C lv2 PRESETS=<sounds> does this into the bundle it builds.

#include <math.h>
#include <stdio.h>
#include <string.h>
#include <sys/stat.h>

#include "p2Lv2Ports.h"
#include "p2Patch.h"

static uint8_t gDumps[P2_PATCH_SLOTS][P2_DUMP_LENGTH];

static void put_string(FILE * f, const char * s) {
    fputc('"', f);

    for (const char * c = s; *c != '\0'; c++) {
        if ((*c == '"') || (*c == '\\')) {
            fputc('\\', f);
        }
        fputc(*c, f);
    }

    fputc('"', f);
}

// The parameters a sound dump carries: a preset sets those and leaves the plug-in's own (Oversampling, Anomalies,
// Hiss, Master Volume) as the player has them
static bool carried(uint32_t id) {
    for (int b = 0; b < P2_SOUND_BYTES; b++) {
        if (gP2SoundBytes[b].paramId == id) {
            return true;
        }
    }

    return false;
}

static void label_of(int number, const char * name, char * out, size_t len) {
    char   trimmed[P2_SOUND_NAME_LENGTH + 1];
    size_t n;

    snprintf(trimmed, sizeof(trimmed), "%s", name);
    n = strlen(trimmed);

    while ((n > 0) && (trimmed[n - 1] == ' ')) {
        trimmed[--n] = '\0';
    }
    snprintf(out, len, "P%03d %s", number, trimmed);
}

static bool copy_file(const char * from, FILE * to) {
    char   buffer[4096];
    size_t n;
    FILE * f = fopen(from, "rb");

    if (f == NULL) {
        return false;
    }

    while ((n = fread(buffer, 1, sizeof(buffer), f)) > 0) {
        fwrite(buffer, 1, n, to);
    }
    fclose(f);
    return true;
}

int main(int argc, char ** argv) {
    struct stat st;
    char        path[4096];
    FILE *      manifest, * presets;
    int         found, written = 0;

    if (argc != 4) {
        fprintf(stderr, "usage: p2Lv2Presets <sounds.syx | folder of NNN Name.syx> <manifest.ttl> <bundle directory>\n");
        return 2;
    }

    if (stat(argv[1], &st) != 0) {
        fprintf(stderr, "p2Lv2Presets: no %s\n", argv[1]);
        return 1;
    }
    found    = S_ISDIR(st.st_mode) ? p2_presets_read_folder(argv[1], gDumps) : p2_presets_read_file(argv[1], gDumps);

    if (found == 0) {
        fprintf(stderr, "p2Lv2Presets: no Pulse 2 sound dumps in %s\n", argv[1]);
        return 1;
    }
    snprintf(path, sizeof(path), "%s/manifest.ttl", argv[3]);
    manifest = fopen(path, "w");
    snprintf(path, sizeof(path), "%s/presets.ttl", argv[3]);
    presets  = fopen(path, "w");

    if ((manifest == NULL) || (presets == NULL) || !copy_file(argv[2], manifest)) {
        fprintf(stderr, "p2Lv2Presets: cannot write the bundle's manifest.ttl and presets.ttl in %s\n", argv[3]);
        return 1;
    }
    fprintf(manifest, "\n@prefix pset: <http://lv2plug.in/ns/ext/presets#> .\n");
    fprintf(presets, "# GENERATED by lv2/p2Lv2Presets.c from %s\n\n"
            "@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .\n"
            "@prefix pset: <http://lv2plug.in/ns/ext/presets#> .\n"
            "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n", argv[1]);

    for (int number = 1; number <= P2_PATCH_SLOTS; number++) {
        uint8_t init[P2_DUMP_LENGTH];
        double  values[kP2ParamCount];
        char    name[P2_SOUND_NAME_LENGTH + 1], label[64];
        bool    first = true;

        // a slot the sounds did not fill reads as INIT: not a preset
        p2_patch_init_dump(number, init);

        if (memcmp(gDumps[number - 1], init, P2_DUMP_LENGTH) == 0) {
            continue;
        }

        for (uint32_t id = 0; id < kP2ParamCount; id++) {
            values[id] = gP2Params[id].defaultNormalized;
        }

        if (!p2_patch_from_syx(gDumps[number - 1], P2_DUMP_LENGTH, values, name)) {
            continue;
        }
        label_of(number, name, label, sizeof(label));

        // notes §15: the URI is the slot's, so a pedalboard that chose P012 still finds it after the sounds change
        fprintf(manifest, "\n<" P2_LV2_URI "-preset-P%03d>\n    a pset:Preset ;\n    lv2:appliesTo <" P2_LV2_URI "> ;\n"
                "    rdfs:label ", number);
        put_string(manifest, label);
        fprintf(manifest, " ;\n    rdfs:seeAlso <presets.ttl> .\n");

        fprintf(presets, "\n<" P2_LV2_URI "-preset-P%03d>\n    a pset:Preset ;\n    lv2:appliesTo <" P2_LV2_URI "> ;\n"
                "    rdfs:label ", number);
        put_string(presets, label);
        fprintf(presets, " ;\n");

        for (uint32_t i = 0; i < gP2Lv2PortCount; i++) {
            const tP2Lv2Port * port  = &gP2Lv2Ports[i];
            double             value = p2_lv2_value(port, values[port->id]);

            if (!carried(port->id)) {
                continue;
            }
            fprintf(presets, "%s[ lv2:symbol \"%s\" ; pset:value ", first ? "    lv2:port " : ",\n             ", port->symbol);

            if (p2_lv2_stepped(port)) {
                fprintf(presets, "%ld ]", lround(value));
            } else {
                fprintf(presets, "%.6f ]", value);
            }
            first = false;
        }

        fprintf(presets, " .\n");
        written++;
    }

    if ((fclose(manifest) != 0) || (fclose(presets) != 0)) {
        fprintf(stderr, "p2Lv2Presets: could not finish writing %s\n", argv[3]);
        return 1;
    }
    printf("p2Lv2Presets: %d preset%s from %s\n", written, (written == 1) ? "" : "s", argv[1]);
    return 0;
}
